void expect_rotation(const Eigen::Matrix3d& m) {
  // Orthonormal with determinant +1 to rounding (entries are sums of three products).
  EXPECT_LE((m * m.transpose() - Eigen::Matrix3d::Identity()).cwiseAbs().maxCoeff(), 1e-15);
  EXPECT_NEAR(m.determinant(), 1.0, 1e-15);
}

const std::array<CivilTime, 4> kEpochsTt{{
    {1957, 10, 4, 19, 28, 34.0},
    {2004, 4, 6, 7, 52, 32.570009},
    {2026, 11, 18, 0, 1, 9.184},
    {2100, 12, 31, 23, 59, 59.0},
}};

TEST(TemeJ2000Test, EveryMatrixIsARotation) {
  for (const CivilTime& c : kEpochsTt) {
    const UtcTime tt = at(c);
    const Nutation nutation = nutation_iau1980(tt);
    const double obliquity = mean_obliquity_iau1980_rad(tt);
    expect_rotation(precession_matrix_iau1976(tt));
    expect_rotation(nutation_matrix(obliquity, nutation));
    expect_rotation(teme_to_j2000_matrix(tt));
  }
}

// Round trips. The matrix is orthonormal to 1e-15, so the round trip returns within a few
// ULPs of |r| = 42164 km (7e-12 km each): 1e-9 km.
TEST(TemeJ2000Test, RoundTrips) {
  const std::array<Eigen::Vector3d, 4> vectors{
      Eigen::Vector3d{5094.18016210, 6127.64465950, 6380.34453270},
      Eigen::Vector3d{-6928.137, 0.0, 0.0}, Eigen::Vector3d{0.0, 0.0, -6928.137},
      Eigen::Vector3d{-30000.0, 29000.0, 1.0}};
  for (const CivilTime& c : kEpochsTt) {
    const UtcTime tt = at(c);
    for (const Eigen::Vector3d& r : vectors) {
      expect_vector_near(j2000_to_teme(teme_to_j2000(r, tt), tt), r, 1e-9);
      expect_vector_near(teme_to_j2000(j2000_to_teme(r, tt), tt), r, 1e-9);
      EXPECT_NEAR(teme_to_j2000(r, tt).norm(), r.norm(), 1e-14 * r.norm());
    }
  }
}

// At J2000.0 (T = 0) every precession angle is exactly zero and P is the identity.
TEST(TemeJ2000Test, NoPrecessionAtJ2000) {
  const UtcTime tt = at(CivilTime{2000, 1, 1, 12, 0, 0.0});
  const PrecessionAngles angles = precession_iau1976(tt);
  EXPECT_EQ(angles.zeta_rad, 0.0);
  EXPECT_EQ(angles.theta_rad, 0.0);
  EXPECT_EQ(angles.z_rad, 0.0);
  EXPECT_EQ(precession_matrix_iau1976(tt), Eigen::Matrix3d::Identity());
  // Mean obliquity at J2000.0: 84381.448 arcsec (Explanatory Supplement 1992, 3.222-1).
  EXPECT_NEAR(mean_obliquity_iau1980_rad(tt), 84381.448 / 3600.0 * kPi / 180.0, 1e-16);
}

// The TEME equation of the equinoxes is d_psi cos(eps_mean) and nothing else.
TEST(TemeJ2000Test, EquationOfEquinoxesHasNoKinematicTerms) {
  for (const CivilTime& c : kEpochsTt) {
    const UtcTime tt = at(c);
    const Nutation nutation = nutation_iau1980(tt);
    const double obliquity = mean_obliquity_iau1980_rad(tt);
    EXPECT_EQ(teme_equation_of_equinoxes_rad(obliquity, nutation),
              nutation.longitude_rad * std::cos(obliquity));
  }
  EXPECT_EQ(teme_equation_of_equinoxes_rad(0.4, Nutation{}), 0.0);
}

// With no nutation, TEME (mean equinox, true = mean equator) is the mean-of-date frame, and
// TEME to J2000 is the inverse precession alone. N = R1(-eps) R1(eps) is the identity only
// to rounding (cos^2 + sin^2 of a rounded cos and sin): 1e-15 is a few ULPs of 1.
TEST(TemeJ2000Test, ZeroNutationLeavesOnlyPrecession) {
  const UtcTime tt = at(kEpochsTt[2]);
  EXPECT_LE(
      (nutation_matrix(0.409, Nutation{}) - Eigen::Matrix3d::Identity()).cwiseAbs().maxCoeff(),
      1e-15);
  const Eigen::Matrix3d m = teme_to_j2000_matrix(tt, Nutation{});
  EXPECT_LE((m - precession_matrix_iau1976(tt).transpose()).cwiseAbs().maxCoeff(), 1e-15);
}

