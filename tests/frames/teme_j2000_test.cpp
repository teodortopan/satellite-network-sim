// All 106 terms, summed largest-last in amplitude order instead of table order: the same
// value to rounding (1e-4 rad sums, 1e-20 rad ULPs).
TEST(TemeJ2000Test, TruncatedSeriesWithAllTermsIsTheFullSeries) {
  for (const CivilTime& c : kEpochsTt) {
    const UtcTime tt = at(c);
    const Nutation full = nutation_iau1980(tt);
    for (const std::size_t count : {kNutationIau1980TermCount, std::size_t{500}}) {
      const Nutation all = nutation_iau1980_largest_terms(tt, count);
      EXPECT_NEAR(all.longitude_rad, full.longitude_rad, 1e-18);
      EXPECT_NEAR(all.obliquity_rad, full.obliquity_rad, 1e-18);
    }
    const Nutation none = nutation_iau1980_largest_terms(tt, 0);
    EXPECT_EQ(none.longitude_rad, 0.0);
    EXPECT_EQ(none.obliquity_rad, 0.0);
  }
}

// The largest term (18.6-year lunar node term: (-17.1996" - 0.01742" T) sin(Omega) in
// longitude, (9.2025" + 0.00089" T) cos(Omega) in obliquity) dominates: the other 105 terms'
// amplitudes add up to 2.2372" in longitude and 0.8737" in obliquity (sums of the absolute
// coefficients of nut80.c), plus under 0.001" from their rates in 1957-2100. So |d_psi| < 17.22"
// + 2.24" and |d_eps| < 9.21" + 0.87".
TEST(TemeJ2000Test, NutationIsBoundedByTheLargestTerm) {
  const double arcsecond_rad = kPi / (180.0 * 3600.0);
  for (const CivilTime& c : kEpochsTt) {
    const Nutation full = nutation_iau1980(at(c));
    EXPECT_LT(std::abs(full.longitude_rad), 19.46 * arcsecond_rad);
    EXPECT_LT(std::abs(full.obliquity_rad), 10.08 * arcsecond_rad);
    const Nutation one = nutation_iau1980_largest_terms(at(c), 1);
    EXPECT_LT(std::abs(one.longitude_rad), 17.22 * arcsecond_rad);
    EXPECT_LT(std::abs(one.obliquity_rad), 9.21 * arcsecond_rad);
    EXPECT_LT(std::abs(full.longitude_rad - one.longitude_rad), 2.24 * arcsecond_rad);
    EXPECT_LT(std::abs(full.obliquity_rad - one.obliquity_rad), 0.88 * arcsecond_rad);
  }
}

