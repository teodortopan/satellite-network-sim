constexpr double kPi = std::numbers::pi;

UtcTime at(const CivilTime& c) {
  const std::optional<UtcTime> t = UtcTime::from_civil(c);
  if (!t.has_value()) {
    ADD_FAILURE() << "invalid fixture date " << c.year << "-" << c.month << "-" << c.day;
    std::abort();
  }
  return *t;
}

Eigen::Vector3d to_eigen(const std::array<double, 3>& v) { return {v[0], v[1], v[2]}; }

void expect_vector_near(const Eigen::Vector3d& actual, const Eigen::Vector3d& expected,
                        double tolerance) {
  EXPECT_NEAR(actual.x(), expected.x(), tolerance);
  EXPECT_NEAR(actual.y(), expected.y(), tolerance);
  EXPECT_NEAR(actual.z(), expected.z(), tolerance);
  EXPECT_LE((actual - expected).norm(), tolerance)
      << "actual " << actual.transpose() << "\nexpected " << expected.transpose();
}

// ---------------------------------------------------------------------------------------
// Against ERFA (tests/frames/erfa_reference.hpp, generated by python/gen_frame_reference.py
// with pyerfa 2.0.1.5: prec76, nut80, obl80, pmat76, numat), at TT epochs from 1965 to 2099.
//
// Both sides evaluate the same published formulas, with the same coefficients, from the
// same two-part Julian date, in double precision. What can differ is rounding: the order
// of a few operations, and sin/cos, which libm computes to within 1 ULP and differently on
// arm64 and x86-64. Measured agreement is given with each tolerance; every tolerance is
// at least 100 times the largest difference seen and still far below anything physical.
// ---------------------------------------------------------------------------------------

// Angles. Precession angles are at most 0.012 rad (one century), nutation 1e-4 rad,
// obliquity 0.41 rad: their rounding errors are below 1e-16 rad. 1e-14 rad is 70 nm at a
// 7000 km radius.
constexpr double kAngleToleranceRad = 1e-14;

// Matrix elements: products and sums of terms of size <= 1, each rounded: a few 1e-16.
constexpr double kMatrixTolerance = 1e-14;

// Rotated vectors: |r| up to 1e4 km, so a few 1e-16 relative is ~1e-12 km. 1e-9 km (1 um)
// leaves room for libm differences; a wrong term of the 106 (0.1 mas = 5e-10 rad) would
// move these vectors by 3e-6 km, so it would still be caught.
constexpr double kPositionToleranceKm = 1e-9;
constexpr double kVelocityToleranceKmS = 1e-12;

TEST(TemeJ2000Test, PrecessionMatchesErfa) {
  for (const ref::Fk5Case& c : ref::kFk5Cases) {
    SCOPED_TRACE(testing::Message() << "TT " << c.tt.year << "-" << c.tt.month << "-" << c.tt.day);
    const UtcTime tt = at(c.tt);
    const PrecessionAngles angles = precession_iau1976(tt);
    EXPECT_NEAR(angles.zeta_rad, c.zeta_rad, kAngleToleranceRad);
    EXPECT_NEAR(angles.theta_rad, c.theta_rad, kAngleToleranceRad);
    EXPECT_NEAR(angles.z_rad, c.z_rad, kAngleToleranceRad);
    const Eigen::Matrix3d p = precession_matrix_iau1976(tt);
    for (Eigen::Index row = 0; row < 3; ++row) {
      for (Eigen::Index column = 0; column < 3; ++column) {
        EXPECT_NEAR(p(row, column),
                    c.precession_matrix.at(static_cast<std::size_t>(row))
                        .at(static_cast<std::size_t>(column)),
                    kMatrixTolerance)
            << "element " << row << ", " << column;
      }
    }
  }
}

TEST(TemeJ2000Test, NutationAndObliquityMatchErfa) {
  for (const ref::Fk5Case& c : ref::kFk5Cases) {
    SCOPED_TRACE(testing::Message() << "TT " << c.tt.year << "-" << c.tt.month << "-" << c.tt.day);
    const UtcTime tt = at(c.tt);
    const Nutation nutation = nutation_iau1980(tt);
    EXPECT_NEAR(nutation.longitude_rad, c.nutation_longitude_rad, kAngleToleranceRad);
    EXPECT_NEAR(nutation.obliquity_rad, c.nutation_obliquity_rad, kAngleToleranceRad);
    EXPECT_NEAR(mean_obliquity_iau1980_rad(tt), c.mean_obliquity_rad, kAngleToleranceRad);
  }
}

TEST(TemeJ2000Test, TemeToJ2000MatchesErfa) {
  for (const ref::Fk5Case& c : ref::kFk5Cases) {
    SCOPED_TRACE(testing::Message() << "TT " << c.tt.year << "-" << c.tt.month << "-" << c.tt.day);
    const UtcTime tt = at(c.tt);
    expect_vector_near(teme_to_j2000(to_eigen(ref::kTemePositionKm), tt),
                       to_eigen(c.j2000_position_km), kPositionToleranceKm);
    expect_vector_near(teme_to_j2000(to_eigen(ref::kTemeStarlinkKm), tt),
                       to_eigen(c.j2000_starlink_km), kPositionToleranceKm);
    expect_vector_near(teme_to_j2000(to_eigen(ref::kTemeVelocityKmS), tt),
                       to_eigen(c.j2000_velocity_km_s), kVelocityToleranceKmS);
    // And back.
    expect_vector_near(j2000_to_teme(to_eigen(c.j2000_position_km), tt),
                       to_eigen(ref::kTemePositionKm), kPositionToleranceKm);
  }
}

// ---------------------------------------------------------------------------------------
// Vallado's TEME "of date" example: Vallado, Crawford, Hujsak & Kelso, "Revisiting
// Spacetrack Report #3", AIAA 2006-6753 Rev 2, Appendix C (CelesTrak PDF, read 2026-11-18).
// Satellite 00005 propagated to 3 days after its TLE epoch, day 182.78495062 of 2000 UTC
// (2000-06-30 18:50:19.733568 UTC):
//   r_TEME  = -9060.47373569   4658.70952502    813.68673153  km
//   v_TEME  =    -2.232832783    -4.110453490    -3.157345433 km/s
//   r_J2000 = -9059.9413786    4659.6972000     813.9588875   km
//   v_J2000 =    -2.233348094    -4.110136162    -3.157394074 km/s
// The paper does not state TT or the nutation series used. TT = UTC + 64.184 s
// (TAI - UTC = 32 s from 1999-01-01 to 2006-01-01, IERS Bulletin C; the paper's own 2004
// example states dAT = 32 s).
//
// These numbers are reproduced only with the nutation series truncated to its 4 largest
// terms, which the paper calls the most common choice (section II.D): then the position
// agrees to 0.47 mm and the velocity to 1e-9 km/s (its last printed digit). With the full
// 106-term series the position differs by 1.139 m, 1.135 m of it along z: the 102 small terms
// change d_psi by -0.057" and d_eps by 0.006" here, and the d_psi part tilts the frame by
// d_psi sin(eps) = 1.1e-7 rad, 1.1 m at this 10220 km radius.
// (Celestial-pole offsets, the other possible difference, move it the wrong way: adding the
// IERS dPsi = -0.055" of that day makes the gap 1.95 m.)
//
// Tolerances: 2 mm for position, four times the 0.47 mm seen (whose cause is not known; his
// TT may carry a different TAI - UTC or one-double Julian date, each worth well under
// 1 mm); 5e-9 km/s for velocity, five times the printed resolution.
// ---------------------------------------------------------------------------------------

UtcTime paper_example_tt() {
  return at(CivilTime{2000, 6, 30, 18, 50, 19.733568}).plus_seconds(64.184);
}
const Eigen::Vector3d kPaperTemeKm{-9060.47373569, 4658.70952502, 813.68673153};
const Eigen::Vector3d kPaperTemeKmS{-2.232832783, -4.110453490, -3.157345433};
const Eigen::Vector3d kPaperJ2000Km{-9059.9413786, 4659.6972000, 813.9588875};
const Eigen::Vector3d kPaperJ2000KmS{-2.233348094, -4.110136162, -3.157394074};

TEST(TemeJ2000Test, ValladoOfDateExampleWithFourTermNutation) {
  const UtcTime tt = paper_example_tt();
  const Eigen::Matrix3d m = teme_to_j2000_matrix(tt, nutation_iau1980_largest_terms(tt, 4));
  expect_vector_near(m * kPaperTemeKm, kPaperJ2000Km, 2e-6);
  expect_vector_near(m * kPaperTemeKmS, kPaperJ2000KmS, 5e-9);
}

TEST(TemeJ2000Test, ValladoOfDateExampleFullSeriesDifference) {
  const UtcTime tt = paper_example_tt();
  const Eigen::Vector3d difference = teme_to_j2000(kPaperTemeKm, tt) - kPaperJ2000Km;
  EXPECT_NEAR(difference.norm(), 1.139e-3, 0.010e-3);
  EXPECT_NEAR(difference.z(), -1.135e-3, 0.010e-3);
}

