"""Print independent reference directions of the Sun for the satsim frames tests, as a C++ header.

Every number comes from pyerfa (ERFA, the BSD-licensed copy of the IAU SOFA library) and numpy,
never from satsim. satsim's frames::sun_direction_* use the Astronomical Almanac's
low-precision formula; the tests check them against these values to about 0.02 degrees.

The reference direction from the Earth's centre to the Sun at a TT instant:

1. erfa.epv00 gives the Earth's heliocentric position and barycentric velocity (BCRS, ICRS
   axes). The geometric direction to the Sun is minus the heliocentric position.
2. erfa.ab applies annual aberration with the Earth's barycentric velocity (the formula's
   longitude includes aberration, about 20.5 arcseconds). Light time (the Sun moves about
   6 km around the barycentre in 8.3 minutes) and the frame bias between ICRS and FK5 J2000
   (0.02 arcseconds) are below 1e-7 rad and ignored.
3. erfa.pmat76 precesses it to the mean equator and equinox of date (MOD); erfa.numat with
   erfa.nut80 and erfa.obl80, then R3(dpsi cos(eps)), takes it to TEME, as in
   python/gen_frame_reference.py.
4. For the Earth-fixed cases, TEME to ITRF: erfa.gmst82 at UT1, then erfa.pom00 (s' = 0).

ERFA's epv00 wants TDB; TT is used (they differ by under 2 ms). Dates are passed as the same
two-part Julian date satsim uses.

Regenerate (inside the CI image, which has pyerfa from python/requirements.txt):

    python3 python/gen_sun_reference.py > tests/frames/sun_reference.hpp
    clang-format -i tests/frames/sun_reference.hpp
"""

import erfa
import numpy as np

NANOSECONDS_PER_DAY = 86_400 * 10**9
ARCSECOND_RAD = np.pi / (180.0 * 3600.0)
TT_MINUS_UTC_S = 69.184

# TT epochs (y, m, d, h, min, s) across the formula's stated range, 1950-2050, including both
# solstices and equinoxes of 2026 and the start and end of the 12-hour Phase 2 run.
EPOCHS_TT = [
    (1950, 1, 7, 7, 12, 0.0),
    (1975, 3, 21, 0, 0, 0.0),
    (2000, 1, 1, 12, 0, 0.0),
    (2013, 9, 22, 18, 30, 0.0),
    (2026, 3, 20, 14, 46, 0.0),
    (2026, 6, 21, 8, 24, 0.0),
    (2026, 9, 23, 0, 5, 0.0),
    (2026, 11, 18, 21, 16, 9.184),
    (2026, 11, 19, 9, 16, 9.184),
    (2026, 12, 21, 20, 50, 0.0),
    (2050, 12, 20, 23, 0, 0.0),
]

# UTC epochs with Earth orientation values (UT1 - UTC in s, x_p and y_p in arcseconds): the
# finals2000A row of 2026-11-18 (tests/time/data/finals2000A_2026q4.txt), used as given.
ECEF_CASES = [
    ((2026, 11, 18, 0, 0, 0.0), (-0.0728860, 0.117290, 0.327387)),
    ((2026, 11, 18, 21, 15, 0.0), (-0.0728860, 0.117290, 0.327387)),
    ((2026, 11, 19, 9, 15, 0.0), (-0.0728860, 0.117290, 0.327387)),
]


def two_part_jd(year, month, day, hour, minute, second, offset_s=0.0):
    """(0h JD of the day, fraction of the day) of a calendar instant plus an offset, at
    nanosecond resolution, the way satsim's UtcTime holds it."""
    jd0, mjd = erfa.cal2jd(year, month, day)
    nanoseconds = (hour * 3600 + minute * 60) * 10**9 + round(second * 1e9)
    nanoseconds += round(offset_s * 1e9)
    days, nanoseconds = divmod(nanoseconds, NANOSECONDS_PER_DAY)
    return float(jd0 + mjd + days), nanoseconds / NANOSECONDS_PER_DAY


def rot3(angle):
    """Frame rotation about z (axes turned by +angle)."""
    c, s = np.cos(angle), np.sin(angle)
    return np.array([[c, s, 0.0], [-s, c, 0.0], [0.0, 0.0, 1.0]])


def num(value):
    """Shortest text that reads back as the same double."""
    return repr(float(value))


def vector(values):
    return "{" + ", ".join(num(v) for v in values) + "}"


def civil(epoch):
    return f"{{{epoch[0]}, {epoch[1]}, {epoch[2]}, {epoch[3]}, {epoch[4]}, {num(epoch[5])}}}"


def sun_mod_and_teme(jd1, jd2):
    """Apparent unit direction to the Sun in MOD and in TEME at TT (jd1 + jd2)."""
    heliocentric, barycentric = erfa.epv00(jd1, jd2)
    to_sun = -heliocentric[0]
    distance_au = np.linalg.norm(to_sun)
    velocity_c = barycentric[1] * erfa.DAU / erfa.DAYSEC / erfa.CMPS
    apparent = erfa.ab(
        to_sun / distance_au, velocity_c, distance_au, np.sqrt(1 - velocity_c @ velocity_c)
    )
    mod = erfa.pmat76(jd1, jd2) @ apparent
    dpsi, deps = erfa.nut80(jd1, jd2)
    eps = erfa.obl80(jd1, jd2)
    teme = rot3(dpsi * np.cos(eps)) @ erfa.numat(eps, dpsi, deps) @ mod
    return mod / np.linalg.norm(mod), teme / np.linalg.norm(teme)


def main():
    out = [
        "#pragma once",
        "",
        "// Generated by python/gen_sun_reference.py with pyerfa "
        f"{erfa.__version__} and numpy {np.__version__}.",
        "// Do not edit; regenerate with the commands in that script's docstring.",
        "",
        "#include <array>",
        "",
        '#include "satsim/time/civil_time.hpp"',
        "",
        "namespace satsim_test::sun_reference {",
        "",
        "using Vector = std::array<double, 3>;",
        "",
        "// TT epochs; apparent unit direction to the Sun in MOD and in TEME.",
        "struct SunCase {",
        "  satsim::time::CivilTime tt{};",
        "  Vector mod{};",
        "  Vector teme{};",
        "};",
        "",
        f"inline const std::array<SunCase, {len(EPOCHS_TT)}> kSunCases{{",
    ]
    for epoch in EPOCHS_TT:
        mod, teme = sun_mod_and_teme(*two_part_jd(*epoch))
        out += [
            "    SunCase{",
            f"        .tt = {civil(epoch)},",
            f"        .mod = {vector(mod)},",
            f"        .teme = {vector(teme)},",
            "    },",
        ]
    out += [
        "};",
        "",
        "// UTC epochs with Earth orientation values; the unit direction to the Sun in ITRF.",
        "struct SunEcefCase {",
        "  satsim::time::CivilTime utc{};",
        "  double ut1_minus_utc_s{};",
        "  double polar_x_arcsec{};",
        "  double polar_y_arcsec{};",
        "  Vector itrf{};",
        "};",
        "",
        f"inline const std::array<SunEcefCase, {len(ECEF_CASES)}> kSunEcefCases{{",
    ]
    for epoch, (ut1_minus_utc, xp_arcsec, yp_arcsec) in ECEF_CASES:
        _, teme = sun_mod_and_teme(*two_part_jd(*epoch, offset_s=TT_MINUS_UTC_S))
        gmst = erfa.gmst82(*two_part_jd(*epoch, offset_s=ut1_minus_utc))
        pom = erfa.pom00(xp_arcsec * ARCSECOND_RAD, yp_arcsec * ARCSECOND_RAD, 0.0)
        itrf = pom @ rot3(gmst) @ teme
        out += [
            "    SunEcefCase{",
            f"        .utc = {civil(epoch)},",
            f"        .ut1_minus_utc_s = {num(ut1_minus_utc)},",
            f"        .polar_x_arcsec = {num(xp_arcsec)},",
            f"        .polar_y_arcsec = {num(yp_arcsec)},",
            f"        .itrf = {vector(itrf)},",
            "    },",
        ]
    out += ["};", "", "}  // namespace satsim_test::sun_reference"]
    print("\n".join(out))


if __name__ == "__main__":
    main()
